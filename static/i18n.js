  function readStored() {
    try {
      var v = window.localStorage.getItem(STORAGE_KEY);
      return SUPPORTED.indexOf(v) >= 0 ? v : null;
    } catch (e) {
      return null;
    }
  }

  function writeStored(lang) {
    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* storage blocked: keep in memory only */ }
  }

  var lang = readStored() || DEFAULT_LANG;
  document.documentElement.setAttribute('lang', lang);

  function has(table, key) {
    return Object.prototype.hasOwnProperty.call(table, key);
  }

  function t(key, vars) {
    var text;
    if (has(DICT[lang], key)) { text = DICT[lang][key]; }
    else if (has(DICT.en, key)) { text = DICT.en[key]; }
    else { text = key; }
    if (vars) {
      text = text.replace(/\{(\w+)\}/g, function (m, name) {
        return has(vars, name) && vars[name] != null ? String(vars[name]) : m;
      });
    }
    return text;
  }

  function applyStatic(root) {
    var scope = root || document;
    Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n]'), function (node) {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-attrs]'), function (node) {
      node.getAttribute('data-i18n-attrs').split(';').forEach(function (pair) {
        var i = pair.indexOf(':');
        if (i > 0) { node.setAttribute(pair.slice(0, i).trim(), t(pair.slice(i + 1).trim())); }
      });
    });
  }

  function setLang(next) {
    if (SUPPORTED.indexOf(next) < 0 || next === lang) { return; }
    lang = next;
    writeStored(lang);
    document.documentElement.setAttribute('lang', lang);
    document.dispatchEvent(new CustomEvent('fm:lang-change', { detail: { lang: lang } }));
    window.location.reload();
  }

  function renderSwitch() {
    var host = document.getElementById('lang-switch');
    if (!host) { return; }
    host.textContent = '';
    host.className = 'lang-switch';
    host.setAttribute('role', 'group');
    host.setAttribute('aria-label', t('i18n.language'));
    [['en', 'EN', 'en'], ['ko', '한국어', 'ko']].forEach(function (item) {
      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'lang-btn';
      btn.textContent = item[1];
      btn.setAttribute('lang', item[2]);
      btn.setAttribute('data-lang', item[0]);
      btn.setAttribute('aria-pressed', item[0] === lang ? 'true' : 'false');
      btn.addEventListener('click', function () { setLang(item[0]); });
      host.appendChild(btn);
    });
  }

  // Same-origin requests carry the chosen language so server messages match the screen.
  var originalFetch = window.fetch;
  if (typeof originalFetch === 'function') {
    window.fetch = function (input, init) {
      try {
        var url = typeof input === 'string' ? input : (input && input.url) || '';
        var sameOrigin = url.charAt(0) === '/' || url.indexOf(window.location.origin + '/') === 0;
        if (sameOrigin) {
          init = init || {};
          var headers = new Headers(init.headers || (typeof input !== 'string' && input && input.headers) || {});
          headers.set('X-FM-Lang', lang);
          init = Object.assign({}, init, { headers: headers });
        }
      } catch (e) { /* never block a request because of the language header */ }
      return originalFetch.call(window, input, init);
    };
  }

  window.FMI18n = { t: t, getLang: function () { return lang; }, setLang: setLang, applyStatic: applyStatic, supported: SUPPORTED.slice() };
  window.t = t;

  function ready() {
    applyStatic(document);
    renderSwitch();
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', ready);
  } else {
    ready();
  }
